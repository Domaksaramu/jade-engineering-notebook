import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, cp, rm, readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { root } from '../scripts/build.mjs';
import { startServer } from '../scripts/dev.mjs';
import { newNote } from '../scripts/content.mjs';

test('HTTP flow: read, new draft, preview, save, publish locally, delete, and reject foreign writes',async t=>{
  const folder=await mkdtemp(path.join(os.tmpdir(),'portfolio-http-'));
  t.after(()=>rm(folder,{recursive:true,force:true}));
  for(const dir of ['src','content'])await cp(path.join(root,dir),path.join(folder,dir),{recursive:true});
  const port=44567,origin=`http://127.0.0.1:${port}`;
  const server=await startServer({projectRoot:folder,port});
  t.after(()=>{server.closeAllConnections();return new Promise(resolve=>server.close(resolve));});
  const get=route=>fetch(origin+route);
  assert.equal((await get('/')).status,200);
  assert.match(await (await get('/studio/')).text(),/type="module"/);
  assert(Array.isArray(await (await get('/content-index.json')).json()));
  const {token}=await (await get('/api/session')).json();
  const post=(route,input,headers={})=>fetch(origin+'/api/'+route,{method:'POST',headers:{Origin:origin,'Content-Type':'application/json','X-CSRF-Token':token,...headers},body:JSON.stringify(input)});
  assert.equal((await post('new',{slug:'http-sample'})).status,201);
  const draft=await (await get('/api/document?kind=notes&slug=http-sample')).json();assert.match(draft.raw,/draft: true/);
  assert.equal((await get('/notes/http-sample/')).status,404);
  const raw=newNote('HTTP 수정 확인').replace('draft: true','draft: false');
  const input={kind:'notes',slug:'http-sample',raw};
  assert.equal((await post('save',input,{Origin:'https://foreign.example'})).status,403);
  assert.equal((await post('save',input,{'X-CSRF-Token':'bad'})).status,403);
  assert.equal((await post('save',input)).status,200);
  assert.match(await (await get('/notes/http-sample/')).text(),/HTTP 수정 확인/);
  const preview=await (await post('preview',input)).json();assert.equal(preview.title,'HTTP 수정 확인');
  assert.match(preview.html,/<h2/);
  assert.equal((await post('delete',input)).status,200);
  assert.equal((await get('/notes/http-sample/')).status,404);
  assert.equal((await readdir(path.join(folder,'.trash'))).length,2);
  assert(!(await readdir(path.join(folder,'dist'))).some(f=>f.startsWith('studio')));
  assert.equal((await post('save',{kind:'notes',slug:'../outside',raw})).status,400);
  assert.match(await readFile(path.join(folder,'content/notes/object-lifetime.md'),'utf8'),/캐시를 넣는 코드/);
});
